  <?php if ($locked && !$done): ?>
    <h1>Instalação concluída</h1>
    <p class="muted">O sistema já está instalado. Por segurança, exclua o arquivo <code>install.php</code> do servidor.</p>
    <a class="btn btn-primary btn-block" href="/admin/">Ir para o painel</a>
  <?php elseif ($done): ?>
    <h1>Tudo pronto! 🎉</h1>
    <p class="muted">Banco criado e administrador cadastrado. <strong>Exclua agora o arquivo <code>install.php</code></strong> pelo Gerenciador de Arquivos da Hostinger.</p>
    <a class="btn btn-primary btn-block" href="/admin/">Acessar o painel</a>
  <?php else: ?>
    <h1>Instalar Integra Code</h1>
    <p class="muted">Crie um banco MySQL no hPanel da Hostinger (Bancos de dados → MySQL) e preencha os dados abaixo.</p>
    <?php if ($error): ?><div class="alert alert-danger"><?= e($error) ?></div><?php endif; ?>
    <form method="post" class="form-grid">
      <fieldset class="span-2"><legend>Site</legend>
        <label>URL do site<input name="app_url" value="<?= e($old['app_url']) ?>" required></label>
      </fieldset>
      <fieldset class="span-2"><legend>Banco de dados MySQL</legend>
        <div class="form-grid">
          <label>Host<input name="db_host" value="<?= e($old['db_host']) ?>" required></label>
          <label>Porta<input name="db_port" value="<?= e($old['db_port']) ?>" required></label>
          <label>Nome do banco<input name="db_name" value="<?= e($old['db_name'] ?? '') ?>" placeholder="u123456789_integra" required></label>
          <label>Usuário<input name="db_user" value="<?= e($old['db_user'] ?? '') ?>" required></label>
          <label class="span-2">Senha<input name="db_pass" type="password" required></label>
        </div>
      </fieldset>
      <fieldset class="span-2"><legend>Administrador</legend>
        <div class="form-grid">
          <label>Nome<input name="admin_name" value="<?= e($old['admin_name'] ?? '') ?>" required></label>
          <label>E-mail<input name="admin_email" type="email" value="<?= e($old['admin_email'] ?? '') ?>" required></label>
          <label class="span-2">Senha (mín. 10 caracteres)<input name="admin_password" type="password" minlength="10" required></label>
        </div>
      </fieldset>
      <fieldset class="span-2"><legend>Segundo administrador (opcional)</legend>
        <div class="form-grid">
          <label>Nome<input name="admin2_name" value="<?= e($old['admin2_name']) ?>"></label>
          <label>E-mail<input name="admin2_email" type="email" value="<?= e($old['admin2_email']) ?>"></label>
          <label class="span-2">Senha (deixe em branco para não criar)<input name="admin2_password" type="password" minlength="10"></label>
        </div>
      </fieldset>
      <fieldset class="span-2"><legend>Asaas (opcional — pode configurar depois no painel)</legend>
        <div class="form-grid">
          <label>Ambiente<select name="asaas_environment" style="width:100%;padding:11px 13px;border-radius:10px;border:1px solid var(--border-strong);background:var(--bg-2)"><option value="production">Produção</option><option value="sandbox">Sandbox</option></select></label>
          <label>Chave da API<input name="asaas_api_key" autocomplete="off" placeholder="$aact_prod_..."></label>
        </div>
      </fieldset>
      <fieldset class="span-2"><legend>IA — Cloudflare Workers AI (opcional)</legend>
        <div class="form-grid">
          <label>Account ID<input name="cloudflare_account_id" autocomplete="off"></label>
          <label>API Token<input name="cloudflare_api_token" autocomplete="off" placeholder="cfat_..."></label>
        </div>
      </fieldset>
      <button class="btn btn-primary btn-block span-2">Instalar</button>
    </form>
  <?php endif; ?>
