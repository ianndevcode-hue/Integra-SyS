<?php
declare(strict_types=1);

/**
 * One-time web installer: writes inc/config.php, creates tables, seeds data, creates the first admin.
 * Locked automatically once inc/config.php exists.
 */

require __DIR__ . '/inc/bootstrap.php';
require INC_PATH . '/content.php';
require_once INC_PATH . '/schema.php';
require INC_PATH . '/seed.php';

$locked = is_installed();
$error = null;
$done = false;
$old = $_POST + ['db_host' => 'localhost', 'db_port' => '3306', 'app_url' => 'https://' . COMPANY['domain'],
    'admin_name' => 'Dev Integra Code', 'admin_email' => 'dev@integra-code.tech', 'admin2_name' => 'Leiva', 'admin2_email' => 'leiva@integra-code.tech'];

if (!$locked && $_SERVER['REQUEST_METHOD'] === 'POST') {
    try {
        $email = mb_strtolower(trim((string)($_POST['admin_email'] ?? '')));
        $password = (string)($_POST['admin_password'] ?? '');
        if (!filter_var($email, FILTER_VALIDATE_EMAIL)) throw new RuntimeException('E-mail do administrador inválido.');
        if (mb_strlen($password) < 10) throw new RuntimeException('A senha do administrador precisa ter pelo menos 10 caracteres.');
        $email2 = mb_strtolower(trim((string)($_POST['admin2_email'] ?? '')));
        $password2 = (string)($_POST['admin2_password'] ?? '');
        if ($password2 !== '' && (!filter_var($email2, FILTER_VALIDATE_EMAIL) || mb_strlen($password2) < 10)) {
            throw new RuntimeException('Segundo administrador: informe um e-mail válido e senha com 10+ caracteres (ou deixe a senha em branco para não criar).');
        }

        $config = [
            'app_url' => rtrim(trim((string)$_POST['app_url']), '/'),
            'app_key' => bin2hex(random_bytes(32)),
            'debug' => false,
            'db' => [
                'driver' => 'mysql',
                'host' => trim((string)$_POST['db_host']),
                'port' => (int)$_POST['db_port'],
                'name' => trim((string)$_POST['db_name']),
                'user' => trim((string)$_POST['db_user']),
                'pass' => (string)$_POST['db_pass'],
            ],
        ];
        $GLOBALS['config'] = $config;
        db(); // throws on bad credentials
        run_migrations();
        seed_base();
        set_setting('schema_version', (string)SCHEMA_VERSION);
        if (!db_value('SELECT id FROM users WHERE email = ?', [$email])) {
            db_insert('users', [
                'name' => trim((string)($_POST['admin_name'] ?? 'Administrador')) ?: 'Administrador',
                'email' => $email, 'password_hash' => password_hash($password, PASSWORD_DEFAULT),
                'role' => 'admin', 'active' => 1, 'created_at' => now(),
            ]);
        }
        if ($password2 !== '' && !db_value('SELECT id FROM users WHERE email = ?', [$email2])) {
            db_insert('users', [
                'name' => trim((string)($_POST['admin2_name'] ?? '')) ?: 'Administrador',
                'email' => $email2, 'password_hash' => password_hash($password2, PASSWORD_DEFAULT),
                'role' => 'admin', 'active' => 1, 'created_at' => now(),
            ]);
        }
        $cfAccount = preg_replace('/[^a-f0-9]/', '', (string)($_POST['cloudflare_account_id'] ?? ''));
        $cfToken = trim((string)($_POST['cloudflare_api_token'] ?? ''));
        if ($cfAccount !== '' && $cfToken !== '') {
            set_setting('cloudflare_account_id', $cfAccount);
            set_setting('cloudflare_api_token', $cfToken);
        }
        $asaasKey = trim((string)($_POST['asaas_api_key'] ?? ''));
        if ($asaasKey !== '') {
            set_setting('asaas_api_key', $asaasKey);
            set_setting('asaas_environment', ($_POST['asaas_environment'] ?? '') === 'sandbox' ? 'sandbox' : 'production');
        }
        $php = "<?php\n// Generated by install.php on " . date('c') . ". Keep this file private.\nreturn " . var_export($config, true) . ";\n";
        if (file_put_contents(INC_PATH . '/config.php', $php, LOCK_EX) === false) {
            throw new RuntimeException('Não foi possível gravar inc/config.php. Verifique as permissões da pasta.');
        }
        @chmod(INC_PATH . '/config.php', 0600);
        $done = true;
    } catch (PDOException $e) {
        $error = 'Falha ao conectar no banco de dados: ' . $e->getMessage();
    } catch (Throwable $e) {
        $error = $e->getMessage();
    }
}
